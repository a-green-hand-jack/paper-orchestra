#!/usr/bin/env python3
"""Create transparent, template-matched evidence-gap manuscripts for blocked Gewu repos.

These are not scientific-result papers.  They are auditable pre-manuscripts that
document why a blocked solution cannot honestly be promoted to a result paper
until the missing raw proof, code, certificate, or data is supplied.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess


ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "datasets/gewu-batch-1838e5e40878/manifest.json"
TEMPLATES = ROOT / "src/templates"


def tex(text: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
        "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
    }
    return "".join(replacements.get(ch, ch) for ch in text)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_project(project: dict, output: Path) -> dict:
    policy = project["field_policy"]
    template_id = policy["template_id"]
    source_template = TEMPLATES / template_id
    target = output / project["id"]
    if target.exists():
        raise FileExistsError(f"refusing to overwrite existing output: {target}")
    target.mkdir(parents=True, mode=0o700)
    document_class = (
        r"\documentclass[11pt]{aomart}" if template_id == "annals-mathematics"
        else r"\documentclass[aps,prl,reprint,nofootinbib]{revtex4-2}"
    )
    bibliography = "plain" if template_id == "annals-mathematics" else "unsrt"
    title = f"Evidence status and reproducibility boundary: {project['title']}"
    reason = project["reason"]
    scope = (
        "This document is an evidence-gap pre-manuscript, not a claim of a new "
        "mathematical or physical result. The source repository does not contain "
        "the raw materials needed to establish the advertised result."
    )
    sections = [
        ("Scope and status", scope),
        ("Admissible context", f"The recorded blocking reason is: {reason}"),
        ("Claim-status boundary", "No theorem, measurement, simulation result, or universal claim is asserted here. Publication artifacts and pointers are not treated as substitute evidence."),
        ("Required evidence for a result paper", "A future result manuscript requires the missing raw proof or derivation, executable verification code or an explicit certificate, and the data or calculation trace needed to reproduce every quantitative claim."),
        ("Reproducibility plan", "When those materials are supplied, the project should be rerun through triage, outline, literature, plotting, section writing, refinement, independent review, and isolated recompilation using the locked domain template and writing style."),
        ("Conclusion", "The correct current status is evidence gap. This document is deliberately conservative and must not be cited as proof that the underlying solution is correct."),
    ]
    body = [
        "% Generated by PaperOrchestra for a blocked Gewu solution; not a result paper.",
        document_class,
        *( [r"\usepackage{amsmath,amssymb}", r"\usepackage{graphicx}", r"\usepackage{hyperref}"]
           if template_id == "physical-review-letters" else [r"\usepackage{amsmath,amssymb,amsthm}"] ),
    ]
    abstract = "\\begin{abstract}This transparent evidence-gap report records why the supplied solution repository cannot currently support an auditable result paper. It preserves the selected target venue and field style without inventing results.\\end{abstract}"
    if template_id == "physical-review-letters":
        body += [r"\begin{document}", f"\\title{{{tex(title)}}}", r"\author{PaperOrchestra evidence audit}", abstract, r"\maketitle"]
    else:
        body += [f"\\title{{{tex(title)}}}", r"\author{PaperOrchestra evidence audit}", r"\begin{document}", r"\maketitle", abstract]
    for heading, paragraph in sections:
        body += [f"\\section{{{tex(heading)}}}", tex(paragraph)]
    body += [r"\nocite{paperorchestraEvidenceGap}", f"\\bibliographystyle{{{bibliography}}}", r"\bibliography{references}", r"\end{document}", ""]
    (target / "main.tex").write_text("\n".join(body), encoding="utf-8")
    (target / "references.bib").write_text(
        "% This is an operational record, not a research citation.\n"
        "@misc{paperorchestraEvidenceGap,\n"
        "  author = {PaperOrchestra},\n"
        "  title = {Evidence-gap report for a blocked Gewu solution},\n"
        "  year = {2026},\n"
        "  note = {Generated status record; not evidence for the underlying claim}\n"
        "}\n", encoding="utf-8")
    (target / "README.md").write_text(
        f"# Evidence-gap pre-manuscript\n\n"
        f"- Project: `{project['id']}`\n"
        f"- Domain: `{policy['research_domain']}`\n"
        f"- Target venue/style: `{policy['target_venue']}` / `{policy['writing_style']}`\n"
        f"- Status: `evidence_gap` (not a scientific-result acceptance)\n\n"
        f"Blocking reason: {reason}\n\n"
        "This package intentionally makes no unsupported scientific claim. Supply the missing raw evidence and rerun the normal PaperOrchestra pipeline before treating it as a result paper.\n",
        encoding="utf-8",
    )
    texlive_bin = "/home/user/texlive/2026/bin/x86_64-linux"
    compile_env = {**os.environ, "PATH": texlive_bin + os.pathsep + os.environ.get("PATH", "")}
    compile_result = subprocess.run(
        ["latexmk", "-norc", "-pdf", "-interaction=nonstopmode", "main.tex"],
        cwd=target, capture_output=True, text=True, timeout=120, env=compile_env,
    )
    report = {
        "schema_version": 1, "kind": "gewu-evidence-gap",
        "project": project["id"], "status": "evidence_gap",
        "research_domain": policy["research_domain"],
        "target_venue": policy["target_venue"], "template_id": template_id,
        "blocking_reason": reason, "latex_exit_code": compile_result.returncode,
        "pdf_present": (target / "main.pdf").is_file(),
        "files": {p.name: digest(p) for p in target.iterdir() if p.is_file()},
    }
    (target / "evidence-gap.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return report


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--project", action="append", dest="projects")
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    blocked = [p for p in manifest["projects"] if p["status"] == "blocked"]
    selected = set(args.projects or [p["id"] for p in blocked])
    unknown = selected - {p["id"] for p in blocked}
    if unknown:
        raise SystemExit("only blocked manifest projects are accepted: " + ", ".join(sorted(unknown)))
    args.output.mkdir(parents=True, exist_ok=True)
    reports = [write_project(p, args.output) for p in blocked if p["id"] in selected]
    print(json.dumps({"kind": "gewu-evidence-gap-batch", "reports": reports}, indent=2))


if __name__ == "__main__":
    main()
